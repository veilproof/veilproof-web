import { describe, it, expect } from "vitest";
import { render, screen } from "@testing-library/react";
import { TrustNotice } from "../src/components/TrustNotice";

// The whole value of the tool is an honest privacy claim. These tests guard
// the copy from silently drifting into overstating it.
describe("TrustNotice", () => {
  it("states that proving happens in the browser, not on a server", () => {
    render(<TrustNotice />);
    expect(screen.getByText(/does not send it to any server/i)).toBeInTheDocument();
  });

  it("states what that claim still rests on", () => {
    render(<TrustNotice />);
    expect(screen.getByText(/trusting the code this page loaded/i)).toBeInTheDocument();
  });

  it("does not claim the secret is safe unconditionally", () => {
    render(<TrustNotice />);
    expect(screen.queryByText(/never leaves your (browser|device)/i)).not.toBeInTheDocument();
    expect(screen.queryByText(/no trust|trustless|impossible|guaranteed/i)).not.toBeInTheDocument();
  });

  it("does not hide the single-party setup or the size of the set", () => {
    render(<TrustNotice />);
    expect(screen.getByText(/generated by a single party/i)).toBeInTheDocument();
    expect(screen.getByText(/at most 16 members/i)).toBeInTheDocument();
  });

  it("says the contract stores only hashes, not identity data", () => {
    render(<TrustNotice />);
    expect(screen.getByText(/never sees or stores raw identity data/i)).toBeInTheDocument();
  });
});
